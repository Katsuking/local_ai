#!/bin/bash
# ==============================================================================
# 音声合成システム ショートカット実行用スクリプト
#
# このスクリプトは、OSのグローバルショートカットキーに登録して使用することを想定しています。
# 実行されると、仮想環境を起動してクリップボード内のテキストを音声合成します。
# ==============================================================================

# 1. スクリプトが置かれているディレクトリを取得し、そこにカレントディレクトリを移動します。
# これにより、config.yaml や venv などの相対パスが正しく解決されます。
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
cd "$SCRIPT_DIR"

# 2. Python 仮想環境をアクティベートします。
# システム全体の Python 環境を汚さず、インストールされた依存パッケージ群を利用します。
if [ -f "venv/bin/activate" ]; then
    source venv/bin/activate
else
    echo "エラー: 仮想環境 (venv) が見つかりません。まず setup.sh を実行してください。"
    exit 1
fi

# 3. メインの Python スクリプトを実行します。
# ショートカットキーから引数が渡された場合（例: run_tts.sh --text "テスト"）にも対応できるよう、"$@" を渡します。
python3 main.py "$@"
